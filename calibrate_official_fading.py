"""Cross-calibrate the UAV A2G small-scale fading model against the official
TR 38.901 CDL generator (MATLAB 5G Toolbox nrCDLChannel).

The paper's small-scale fading is implemented in ``channel_38901_fading.py``
following the normative 38.901 CDL construction (ULA-Los K = 7 dB).  This
script loads the fading series generated by the *official* 5G Toolbox CDL
generator (``D:/matlab_work/cdl_data.json``: CDL-D = LOS/Rician, CDL-A =
NLOS/Rayleigh) and asks two questions:

  1. Does the official generator recover a Rician K in the same 7-9 dB band as
     our ULA-Los assumption?  (validates the K calibration)
  2. Does the "link is time-varying -> re-optimize every step" conclusion of the
     paper hold under the official generator, or is it an artefact of our
     self-written CDL?  (validates the core empirical claim, cv of the rate)

Outputs: ``calib_official.json`` (table) and ``calib_official.png`` (figure).
"""
import json
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import channel_3gpp as ch3g
import channel_38901_fading as chfade

JSON_IN = Path("D:/matlab_work/cdl_data.json")
OUT_JSON = Path(__file__).resolve().parent / "calib_official.json"
OUT_PNG = Path(__file__).resolve().parent / "calib_official.png"

F_CARRIER = ch3g.F_HZ
B_PER_LINK_HZ = ch3g.B_REF_HZ / 3.0      # 3 links share 10 MHz
V_MAX = 10.0
FD_SELF = V_MAX * ch3g.F_C / F_CARRIER    # Doppler used by the self-written model


def kestimator(f_power):
    """Rician K (dB) from a fading-power realisation (mean-normalised)."""
    f = np.asarray(f_power, float)
    f = f / f.mean()
    m = f.mean()
    v = f.var()
    if m <= 0 or v <= 0:
        return -999.0
    # K = |E[h]|^2 / var(h); with f=|h|^2 mean-normalised, use the standard
    # moment form g = 2 E[R^2]/E[R]^2 -> K = 1/(g-2) on the amplitude.
    R = np.sqrt(np.abs(f))
    rbar = R.mean()
    r2bar = (R ** 2).mean()
    g = 2.0 * r2bar / max(rbar ** 2, 1e-12)
    if g <= 2.0:
        return -999.0
    return 10.0 * np.log10(1.0 / (g - 2.0))


def rate_cv_at_nominal(g_macro, f_power, target_rate=46.0):
    """Rate coefficient of variation when the link sits at a nominal operating
    point and only the small-scale fading varies."""
    f = np.asarray(f_power, float) / np.mean(f_power)
    # choose p so mean rate == target (mean of f is 1)
    p = (2.0 ** (target_rate / (B_PER_LINK_HZ / 1e6)) - 1.0) / max(g_macro, 1e-12)
    p = float(np.clip(p, 0.01, 1.0))
    R = (B_PER_LINK_HZ / 1e6) * np.log2(1.0 + p * g_macro * f)   # Mb/s
    return dict(p_W=p, mean_R=R.mean(), cv_R=R.std() / R.mean(),
                r_min=R.min(), r_max=R.max())


def main():
    blob = json.loads(JSON_IN.read_text(encoding="utf-8"))

    # ---- nominal operating point (LOS, d3D=150 m, h=100 m) ----------------
    uav = np.array([[100.0, 100.0, 100.0]])
    usr = np.array([[250.0, 100.0, 0.0]])     # d2D=150, d3D=150 (flat-ish)
    los = np.array([[True]])
    pl = float(ch3g.path_loss_db(F_CARRIER, uav, usr, los)[0, 0])
    g_macro = float(ch3g.gain_from_db(pl, d_ref=None, f_hz=F_CARRIER,
                                      b_ref_hz=B_PER_LINK_HZ))

    # ---- official series ----------------------------------------------------
    off_los = np.asarray(blob["LOS"]["f_power"], float)
    off_nlos = np.asarray(blob["NLOS"]["f_power"], float)
    off_los = off_los[:1992]
    off_nlos = off_nlos[:1992]

    # ---- self-written ULA-Los series (K = 7 dB) ----------------------------
    h_self = chfade.fast_fading_series(
        seed=991, n_snapshots=1992, k_factor_db=chfade.ULA_LOS_K_FACTOR_DB,
        max_doppler_hz=FD_SELF)
    self_f = np.abs(h_self) ** 2
    # NLOS branch: pure Rayleigh (K=0), mirrors official CDL-A deep fades
    h_self_nlos = chfade.nlos_rayleigh_series(
        seed=992, n_snapshots=1992, max_doppler_hz=FD_SELF)
    self_nlos_f = np.abs(h_self_nlos) ** 2

    models = [
        ("Official CDL-D (LOS, Rician K=9 dB)", off_los,
         float(blob["LOS"]["KFactor_declared_dB"])),     # 9 dB declared
        ("Official CDL-A (NLOS, Rayleigh K=0 dB)", off_nlos, 0.0),  # NLOS
        ("Self-written ULA-Los (Rician K=7 dB)", self_f,
         float(chfade.ULA_LOS_K_FACTOR_DB)),              # 7 dB (Table 7.8.3-1)
        ("Self-written NLOS (Rayleigh K=0 dB)", self_nlos_f,
         float(chfade.ULA_NLOS_K_FACTOR_DB)),             # 0 dB (CDL-A mirror)
    ]

    rows = []
    print("=== small-scale fading cross-check (TR 38.901) ===")
    print(f"{'model':42s} {'K[dB]':>7s} {'cv(f^2)':>9s} {'cv(R)':>9s} "
          f"{'Rmin/Rmax':>14s}")
    for name, f, K in models:
        rc = rate_cv_at_nominal(g_macro, f)
        rows.append({"model": name, "K_dB": K,
                     "cv_f2": float(f.std() / f.mean()),
                     "cv_R": rc["cv_R"], "Rmin": rc["r_min"], "Rmax": rc["r_max"]})
        print(f"{name:42s} {K:7.1f} {f.std()/f.mean():9.3f} {rc['cv_R']:9.3f} "
              f"{rc['r_min']/rc['r_max']:14.3f}")

    # ---- realistic geometry: official vs self fading, with shadow ----------
    # Draw UAV positions inside the 200x200 operating area at many sampled
    # steps and report the *realised-rate distribution* when fading is supplied
    # by the official CDL generator (LOS/NLOS split by P_LOS) versus the
    # self-written model.  To make the deep-fade tail a low-variance, fair
    # statistic we use N_SAMP = 2000 independent geometry steps; the fading
    # series is cycled by modulo (legitimate because each step is an
    # independent coherence-time realisation) and we report percentiles
    # alongside the mean / cv.  This is the faithful "plug the official
    # generator into the pipeline" test of the paper's core claim (link is
    # time-varying -> must re-optimize every step).
    from sim_analysis_3gpp import (N_UAV, N_USER, make_users, B_TOTAL,
                                   CHANNEL_SEED, SHADOW_SIGMA)
    from channel_38901_fading import SHADOW_CORR_DISTANCE_M
    N_SAMP = 2000
    users = make_users()
    rng = np.random.default_rng(2024)
    b_mhz = B_TOTAL / N_UAV                       # MHz per link (rate in Mb/s)
    p = 0.3

    # short correlated-shadow trajectories (40 samples) for the 3 UAVs
    traj = np.zeros((N_SAMP, N_UAV, 3))
    traj[..., 0] = np.linspace(50, 150, N_SAMP)[:, None]
    traj[..., 1] = 100.0
    traj[..., 2] = 100.0
    sf = np.stack([
        chfade.correlated_shadow_fading(traj[:, k, :], SHADOW_SIGMA,
                                        SHADOW_CORR_DISTANCE_M, seed=CHANNEL_SEED + k)
        for k in range(N_UAV)], axis=1)            # (N_SAMP, N_UAV)

    def realised_rate_cv(fading_los, fading_nlos, use_self=False,
                         split_nlos=True, seed=7):
        r = np.random.default_rng(seed)
        L = len(fading_los)
        rates = []
        for t in range(N_SAMP):
            uavs = r.uniform([40, 40, 50], [160, 160, 150], size=(N_UAV, 3))
            G = ch3g.channel_gains(uavs, users, f_hz=F_CARRIER, shadow_sigma=0.0,
                                   seed=t, los_override=None, b_ref_hz=B_PER_LINK_HZ)
            G = G * (10.0 ** (-sf[t] / 10.0))[:, None]
            d2 = np.sqrt(((uavs[:, None, :2] - users[None, :, :2]) ** 2).sum(-1))
            p_los = ch3g.los_probability(d2, uavs[:, 2][:, None])
            is_los = (r.random((N_UAV, N_USER)) < p_los)
            if use_self and not split_nlos:
                # legacy Rician-LOS-only branch (no NLOS deep fades)
                fl = np.broadcast_to(fading_los[t % L], (N_UAV, N_USER))
            else:
                fl = np.where(is_los, fading_los[t % L], fading_nlos[t % L])
            G = G * fl
            g_sel = G.max(axis=1)
            R = b_mhz * np.log2(1.0 + p * g_sel)   # Mb/s
            rates.append(R.mean())
        rates = np.array(rates)
        return (rates.mean(), rates.std() / rates.mean(),
                rates.min(), rates.max(), rates)

    m_off = realised_rate_cv(off_los, off_nlos, use_self=False)
    m_self_r = realised_rate_cv(self_f, self_f, use_self=True, split_nlos=False)
    m_self_m = realised_rate_cv(self_f, self_nlos_f, use_self=True, split_nlos=True)

    def _p5p95(m):
        rr = np.sort(m[4])
        return float(np.percentile(rr, 5)), float(np.percentile(rr, 95))

    p_off = _p5p95(m_off)
    p_sr = _p5p95(m_self_r)
    p_sm = _p5p95(m_self_m)
    print("\n=== realistic geometry realised-rate distribution "
          "(large-scale + shadow + fading, N=%d) ===" % N_SAMP)
    print(f"  {'model':26s} {'mean':>6s} {'cv':>6s} {'p5':>6s} {'p95':>6s} "
          f"{'min':>7s} {'max':>7s}")
    for lab, m, pp in [("official CDL", m_off, p_off),
                       ("self Rician-LOS-only", m_self_r, p_sr),
                       ("self mixed LOS/NLOS", m_self_m, p_sm)]:
        print(f"  {lab:26s} {m[0]:6.1f} {m[1]:6.3f} {pp[0]:6.1f} {pp[1]:6.1f} "
              f"{m[2]:7.1f} {m[3]:7.1f}")
    rows.append({"model": "trajectory-official", "mean_R_Mbps": m_off[0],
                 "cv_R": m_off[1], "p5_R": p_off[0], "p95_R": p_off[1],
                 "Rmin": m_off[2], "Rmax": m_off[3]})
    rows.append({"model": "trajectory-self-rician-only", "mean_R_Mbps": m_self_r[0],
                 "cv_R": m_self_r[1], "p5_R": p_sr[0], "p95_R": p_sr[1],
                 "Rmin": m_self_r[2], "Rmax": m_self_r[3]})
    rows.append({"model": "trajectory-self-mixed", "mean_R_Mbps": m_self_m[0],
                 "cv_R": m_self_m[1], "p5_R": p_sm[0], "p95_R": p_sm[1],
                 "Rmin": m_self_m[2], "Rmax": m_self_m[3]})

    OUT_JSON.write_text(json.dumps(rows, indent=2), encoding="utf-8")

    # ---- figure ------------------------------------------------------------
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.8))
    ax = axes[0]
    for name, f, K in models:
        ff = f / f.mean()
        ax.hist(ff, bins=60, density=True, histtype="step", linewidth=1.4,
                label=name.replace(" (", "\n("))
    ax.set_xlabel(r"normalised small-scale gain $|h|^2 / \mathbb{E}[|h|^2]$")
    ax.set_ylabel("probability density")
    ax.set_title("(a) Fading-power distribution (TR 38.901)")
    ax.legend(fontsize=7); ax.grid(alpha=0.3)
    ax.set_ylim(0, 1.4)

    ax = axes[1]
    for name, f, K in models:
        ff = f / f.mean()
        p = (2.0 ** (46.0 / (B_PER_LINK_HZ / 1e6)) - 1.0) / g_macro
        R = (B_PER_LINK_HZ / 1e6) * np.log2(1.0 + p * g_macro * ff)
        ax.hist(R, bins=60, density=True, histtype="step", linewidth=1.4,
                label=name.replace(" (", "\n("))
    ax.axvline(46.0, ls="--", color="k", alpha=0.5, label="target 46 Mb/s")
    ax.set_xlabel("realised link rate [Mb/s]")
    ax.set_ylabel("probability density")
    ax.set_title("(b) Resulting rate distribution (nominal op. point)")
    ax.legend(fontsize=7); ax.grid(alpha=0.3)

    # panel (c): realised-rate CDF for the three trajectory models
    ax = axes[2]
    for lab, m in [("official CDL (LOS/NLOS)", m_off),
                   ("self Rician-LOS-only", m_self_r),
                   ("self mixed LOS/NLOS", m_self_m)]:
        rr = np.sort(m[4])
        cdf = np.arange(1, len(rr) + 1) / len(rr)
        ax.plot(rr, cdf, linewidth=1.4, label=lab)
    ax.set_xlabel("realised mean link rate [Mb/s]")
    ax.set_ylabel("empirical CDF")
    ax.set_title("(c) Realised-rate CDF (40-step trajectories)")
    ax.legend(fontsize=7); ax.grid(alpha=0.3); ax.set_ylim(0, 1.02)
    fig.tight_layout()
    plt.savefig(OUT_PNG, dpi=150)
    plt.close()
    print(f"\n[write] {OUT_JSON.name} , {OUT_PNG.name}")


if __name__ == "__main__":
    main()
